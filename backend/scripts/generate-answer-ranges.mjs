import { writeFile } from "node:fs/promises";
// Goja currently accepts Unicode property escapes without matching them correctly.
// Commit the explicit table so judge behavior never depends on regex-engine support.
const ranges = [];
const pattern = /[\p{White_Space}\p{Punctuation}]/u;
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (!pattern.test(String.fromCodePoint(cp))) continue;
  const prior = ranges.at(-1);
  if (prior && prior[1] === cp - 1) prior[1] = cp;
  else ranges.push([cp, cp]);
}
await writeFile(
  new URL("../pb_hooks/lib/answer-ranges.js", import.meta.url),
  `// Generated by scripts/generate-answer-ranges.mjs; Unicode ${process.versions.unicode}.\n// White_Space and Punctuation code point ranges. Do not edit manually.\nmodule.exports = ${JSON.stringify(ranges)};\n`,
);
console.log(
  `Generated ${ranges.length} answer-normalization ranges (Unicode ${process.versions.unicode}).`,
);
